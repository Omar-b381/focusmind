export const buildKnowledgeConnectorPrompt = (
  newConcepts: string[],
  existingConcepts: { id: string; concept: string }[]
): string => `
أنت مهندس معرفة خبير تبني شبكة مفاهيم مترابطة (Concept Map). مهمتك هي العثور على العلاقات والروابط المنطقية بين المفاهيم الجديدة والمفاهيم الموجودة مسبقاً في شبكة معرفة الطالب.

المفاهيم الجديدة المراد إضافتها:
${newConcepts.map((c, i) => `${i + 1}. ${c}`).join('\n')}

المفاهيم الموجودة مسبقاً في الخريطة:
${existingConcepts.map(c => `- [ID: ${c.id}] ${c.concept}`).join('\n')}

المطلوب: تحديد العلاقات المفاهيمية (أي مفهوم يؤدي إلى الآخر، أو أي مفهوم يعد شرطاً مسبقاً أو جزءاً من الآخر).

تنسيق المخرجات:
يجب إرجاع الإجابة بصيغة JSON فقط بهذا الهيكل دون أي نصوص إضافية:
{
  "connections": [
    {
      "sourceConcept": "اسم المفهوم الجديد أو المعرف الخاص به",
      "targetConceptId": "معرف (ID) المفهوم القديم المتربط به",
      "relationType": "نوع العلاقة (مثال: 'شرط مسبق'، 'تطبيق عملي'، 'مفهوم فرعي')"
    }
  ]
}
`;
