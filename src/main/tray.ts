import { app, Menu, Tray, BrowserWindow, nativeImage } from 'electron'
import { join } from 'path'

let tray: Tray | null = null

export function createTray(mainWindow: BrowserWindow): Tray {
  const iconPath = join(__dirname, '../../resources/icon.png')
  
  let image = nativeImage.createFromPath(iconPath)
  if (image.isEmpty()) {
    // 16x16 transparent PNG dot fallback
    image = nativeImage.createFromBuffer(Buffer.from([
      0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
      0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x10, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0xF3, 0xFF,
      0x61, 0x00, 0x00, 0x00, 0x09, 0x70, 0x48, 0x59, 0x73, 0x00, 0x00, 0x0E, 0xC4, 0x00, 0x00, 0x0E,
      0xC4, 0x01, 0x95, 0x2B, 0x0E, 0x1B, 0x00, 0x00, 0x00, 0x18, 0x49, 0x44, 0x41, 0x54, 0x38, 0x8D,
      0x63, 0xFC, 0xCF, 0xC0, 0xF0, 0x1F, 0x0C, 0x0C, 0x0C, 0x02, 0x43, 0x30, 0x30, 0x12, 0x0D, 0x62,
      0x83, 0x06, 0x00, 0xD4, 0x54, 0x01, 0x21, 0xEF, 0xE7, 0x2B, 0xD5, 0x00, 0x00, 0x00, 0x00, 0x49,
      0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82
    ]))
  }

  tray = new Tray(image)

  const contextMenu = Menu.buildFromTemplate([
    {
      label: 'فتح FocusMind',
      click: () => {
        mainWindow.show()
      }
    },
    { type: 'separator' },
    {
      label: 'بدء مؤقت التركيز ⏱️',
      click: () => {
        mainWindow.webContents.send('hotkey:focus-timer')
      }
    },
    {
      label: 'تفريغ ذهني سريع (Brain Dump) 🧠',
      click: () => {
        mainWindow.webContents.send('hotkey:brain-dump')
      }
    },
    { type: 'separator' },
    {
      label: 'إغلاق التطبيق',
      click: () => {
        app.quit()
      }
    }
  ])

  tray.setToolTip('FocusMind')
  tray.setContextMenu(contextMenu)

  tray.on('click', () => {
    if (mainWindow.isVisible()) {
      mainWindow.hide()
    } else {
      mainWindow.show()
      mainWindow.focus()
    }
  })

  return tray
}
